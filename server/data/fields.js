export const CAREER_FIELDS = FIELD_CATALOG.map((f) => f.name);
export const SOFT_SKILLS = ['Communication', 'Leadership', 'Teamwork', 'Problem Solving', 'Time Management', 'Adaptability', 'Critical Thinking', 'Creativity', 'Negotiation', 'Public Speaking'];

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const compiled = FIELD_CATALOG.filter((f) => f.name !== 'Other').map((f) => ({
  name: f.name, roles: f.roles.map((r) => r.toLowerCase()),
  rx: f.keywords.map((k) => new RegExp(`(^|[^a-z0-9])${esc(k.trim())}`, 'i')), // prefix match so "nurs" matches nurse/nursing
}));

// Which career fields does a job belong to? Used for filtering and match scoring.
export function classifyFields({ title = '', description = '', skills = [], sector } = {}) {
  const t = title.toLowerCase(), d = `${description.slice(0, 1500)} ${skills.join(' ')}`.toLowerCase();
  const scored = compiled.map((f) => {
    let s = 0;
    f.rx.forEach((rx) => { if (rx.test(t)) s += 3; else if (rx.test(d)) s += 1; });
    f.roles.forEach((r) => { if (t.includes(r)) s += 4; });
    return [f.name, s];
  }).filter(([, s]) => s >= 3).sort((a, b) => b[1] - a[1]).slice(0, 2).map(([n]) => n);
  if (!scored.length && sector === 'government') return ['Government / Public Administration'];
  return scored;
}
